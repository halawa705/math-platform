const LEAK_WORDS =
  /\b(frac|dfrac|sqrt|text|textbf|mathrm|mathbb|displaystyle|begin|end|cases|quad|qquad|cdot|times|div|overline|widehat|Delta|angle|circ|xrightarrow|rightarrow|Rightarrow|implies|approx|infty|setminus|sim|cong|sum|bar|left|right)\b/;

function assertZeroMathLeakInText(text: string | undefined, label: string): void {
  if (!text) return;
  const html = renderToStaticMarkup(
    React.createElement(SafeKaTeXBiDiMathRenderer, {
      text,
      numeralMode: "western",
      notationLanguage: "english",
    })
  );
  const visible = html
    .replace(/<[^>]+>/g, "")
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#x27;/g, "'");
  expect(html, `${label} katex-error`).not.toContain("katex-error");
  expect(visible, `${label} backslash`).not.toMatch(/\\/);
  expect(visible, `${label} dollar`).not.toMatch(/\$/);
  expect(visible, `${label} latex word`).not.toMatch(LEAK_WORDS);
  expect(visible, `${label} metadata tag`).not.toMatch(/معرف\s*(?:السؤال|المثال|الفكرة)|نوع\s*المسألة|رسم\s*(?:هندسي|بياني)/);
}

