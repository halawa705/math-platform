describe("polygons lesson system-wide geometry, parser & diagram guard", () => {
  const items = mergeBookletThreeStagesRepliesToPrintableItems({
    stage1Raw: STAGE1_SAMPLE,
    stage2Raw: STAGE2_SAMPLE,
    branchId: "plane_geometry",
    branchNameAr: "الهندسة المستوية",
    unitId: "u3",
    lessonId: "l1",
    lessonTitleArabic: "المضلعات",
    gradeId: "prep-1",
    stage: "preparatory",
  });

  it("blocks bogus diagrams on counting, symmetry, and theoretical questions", () => {
    const noDiagramPrompts = ["قُسم مضلع محدب", "عدد المثلثات الناتجة", "إجمالي عدد أقطار", "عدد محاور التماثل لكل من", "قارن في جدول"];
    for (const needle of noDiagramPrompts) {
      const q = items.find((item) => item.promptAr.includes(needle));
      expect(q, `Expected item for ${needle}`).toBeDefined();
      expect(q?.geometryFigure, `Unexpected diagram for ${needle}`).toBeUndefined();
    }
  });

  it("never misclassifies multi-part (أ، ب، جـ، د) drills as MCQ", () => {
    const drill25 = items.find((item) => item.promptAr.includes("اذكر عدد محاور التماثل"));
    expect(drill25).toBeDefined();
    expect(drill25?.kind).not.toBe("mcq");
    expect(drill25?.mcqChoicesAr).toBeUndefined();
  });

  it("renders concave, algebraic, parallel, adjacent, cross, and extended polygons cleanly without self-intersection", () => {
    const visualNeedles = [
      "m(\\angle D) = 20x",
      "وزاويتان قياس كل منهما يساوي",
      "m(\\angle C) = 150",
      "يشتركان في الضلع",
      "ملاصقاً لمضلع ثماني منتظم",
      "خارج السداسي",
      "منعكسة",
      "27x",
      "في النقطة $Z$ خارج السداسي",
      "المثلث $ABM$ متساوي الساقين",
      "مثلثاً كبيراً $XYZ$",
      "صليب متماثل",
      "خماسي مقعر $ABCDE$",
    ];
    for (const needle of visualNeedles) {
      const q = items.find((item) => item.promptAr.includes(needle));
      expect(q, `Missing item for ${needle}`).toBeDefined();
      expect(q?.geometryFigure, `Missing geometryFigure for ${needle}: ${q?.figureDiagnosticsAr?.join(" | ")}`).toBeDefined();
      expect(hasFigurePolygonSelfIntersection(q!.geometryFigure!)).toBe(false);
      const svg = projectGeometryFigureToSVGMarkup(q!.geometryFigure!, {});
      expect(svg).toContain("<svg");
      expect(svg).toContain("<polygon");
    }
  });

  it("renders reflex arc flag=1 and handles octagon+square without falling back to standalone square", () => {
    const octSq = matchGeometryWithDiagnostics(
      {
        geometryTag: "الرؤوس (ABCDEFGH ثماني منتظم ; JHGI مربع يشتركان في الرأس H) ؛ المطلوب: قياس ∠JHA",
        problemPrompt: "في الشكل المقابل، رُسم مربع JHGI ملاصقاً لمضلع ثماني منتظم ABCDEFGH ومشتركاً معه في الرأس H.",
      },
      "oct_sq_test"
    );
    expect(octSq.decision).toBe("green");
    expect(octSq.figure?.vertices.length).toBeGreaterThanOrEqual(10);

    const reflexRes = matchGeometryWithDiagnostics(
      {
        geometryTag: "الرؤوس (شكل رباعي ABCD) ؛ الزوايا والتعامد (m(منعكسة ∠BCD) = 215°) ؛ المطلوب: إثبات أن ABCD مقعر",
        problemPrompt: "في الشكل المقابل، ABCD شكل رباعي فيه قياس الزاوية المنعكسة m(منعكسة ∠BCD) = 215°.",
      },
      "reflex_test"
    );
    expect(reflexRes.decision).toBe("green");
    const svg = projectGeometryFigureToSVGMarkup(reflexRes.figure!, {});
    expect(svg).toContain(" 1 ");
  });
});
