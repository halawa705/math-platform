/**
 * @file polygon-clause-restructurer-helper.ts
 * @description مساعد ذري لتطبيع صيغ المضلعات العامة والمقعرة والمتجاورة وأقطارها وامتداداتها قبل التقسيم إلى حقائق.
 * @invariant ملف ذري مستقل باسم فريد عالمياً وفق دستور المنصة (AGENTS.md) (<= 115 سطراً).
 */

export const MODULE_ID_POLYGON_CLAUSE_RESTRUCTURER_HELPER =
  "polygon_clause_restructurer_helper" as const;

const SEP = " ؛ ";

/**
 * يعيد صياغة الجمل الخاصة بالمضلعات (خماسي/سداسي/سباعي/ثماني، مقعر، متجاور، أقطار، وامتدادات)
 * إلى جمل حقائق قياسية يفهمها `geo-fact-parser.ts` دون تضخيم `geometry-clause-restructurer.ts`.
 */
export function restructurePolygonAndExtensionClauses(input: string): string {
  let out = input;

  // 1. صليب متماثل ذو 8 أضلاع أو مضلع غير محدب صريح
  out = out.replace(
    /(?:مضلع\s+)?ذو\s+8\s+أضلاع\s+على\s+شكل\s+صليب\s+متماثل/g,
    `ثماني مقعر ABCDEFGH${SEP}ق(∠A) = 90°${SEP}ق(∠B) = 90°${SEP}ق(∠C) = 90°${SEP}ق(∠D) = 270°${SEP}ق(∠E) = 90°${SEP}ق(∠F) = 90°${SEP}ق(∠G) = 270°${SEP}ق(∠H) = 90°`
  );

  // 2. المضلعات غير المسماة المتجاورة أو المشتركة في رأس أو ضلع
  out = out
    .replace(
      /خماسي\s+منتظم\s+وسداسي\s+منتظم\s+يشتركان\s+في\s+(?:ال)?رأس\s+([A-Z])\s+و(?:ال)?ضلع\s*(?:ال)?مشترك/g,
      `خماسي منتظم $1ABKL${SEP}سداسي منتظم $1ACDEF${SEP}ق(∠L$1F) = ؟`
    )
    .replace(
      /سداسيان\s+منتظمان(?:\s+متطابقان)?\s+يشتركان\s+في\s+(?:ال)?ضلع\s*([A-Z]{2})/g,
      (_m, ab: string) => `سداسي منتظم ${ab}CDEF${SEP}سداسي منتظم ${ab}GHIJ${SEP}ق(∠F${ab[0]}J) = ؟`
    )
    .replace(
      /خماسي\s+منتظم\s+ومثلث\s+متساوي\s+الأضلاع\s+يشتركان\s+في\s+(?:ال)?ضلع\s*([A-Z]{2})(?:\s*و(?:ال)?رأس\s*[A-Z])?/g,
      (_m, ab: string) => `خماسي منتظم ${ab}CDE${SEP}مثلث ${ab}F متساوي الأضلاع${SEP}ق(∠E${ab[0]}F) = ؟`
    )
    .replace(
      /المستقيمان\s+([A-Z]{2})\s+و\s+([A-Z]{2})\s+يتقاطعان\s+في\s+(?:النقطة\s+)?([A-Z])\s+خارج\s+مضلع\s+خماسي[^؛.\n]*?(?:(\d+(?:\.\d+)?)\s*°)?/g,
      (_m, l1: string, l2: string, pt: string, deg?: string) => {
        const b = l1.replace(pt, "")[0] || "B";
        const d = l2.replace(pt, "")[0] || "D";
        const aEnd = l1.replace(b, "") || "A";
        const cEnd = l2.replace(d, "") || "C";
        const ang = deg || "50";
        return `خماسي ${pt}${b}EF${d}${SEP}نمد ${b}${pt} إلى ${aEnd}${SEP}نمد ${d}${pt} إلى ${cEnd}${SEP}${l1} ∩ ${l2} = {${pt}}${SEP}ق(∠${b}${pt}${d}) = ${ang}°${SEP}ق(∠${aEnd}${pt}${cEnd}) = ${ang}°`;
      }
    )
    .replace(/(?:؛\s*)?(?:بحيث\s+)?نشأت\s+زوايا\s+متقابلة\s+بالرأس[^؛.\n]*[؛.]?/g, " ")
    .replace(/(?:؛\s*)?(?:إذا\s+كانت\s+)?الزاوية\s+المتقابلة\s+معها[^؛.\n]*[؛.]?/g, " ")
    .replace(/(?:؛\s*)?(?:وكانت\s+)?بقية\s+زوايا\s+الخماسي[^؛.\n]*[؛.]?/g, " ")
    .replace(
      /مضلع\s+خماسي\s+فيه\s+ضلعان\s+(?:متوازيان|\/\/)(?:\s+يصنعان\s+مع\s+القاطع\s+زاويتين\s+داخلتين\s+متكاملتين)?/g,
      `خماسي ABCDE${SEP}AE // BC`
    );

  // 3. إزالة ذيل "يشتركان في الرأس ... والضلع ..." بعد المضلعات المسماة حتى لا يعطل المحلل دون ابتلاع الفواصل التالية
  out = out.replace(
    /(?:\s*و)?يشتركان\s+في\s+(?:ال)?(?:رأس|ضلع)\s*(?:واحد\s+)?(?:[A-Z]{1,2})?(?:\s*و(?:ال)?(?:رأس|ضلع)\s*[A-Z]{1,2})?/g,
    " "
  );

  // 4. أقطار المضلعات (مثنى وجمع وتوصيل رؤوس بالأقطار)
  out = out
    .replace(
      /(?:ر[َُ]?سم|نرسم|ارسم|وصل)\s+(?:ال)?قطر(?:ان|ين)\s+([A-Z]{2})\s*و\s*([A-Z]{2})/g,
      `${SEP}ارسم $1${SEP}ارسم $2`
    )
    .replace(
      /تقاطع\s+(?:ال)?قطر(?:ان|ين)\s+([A-Z]{2})\s*و\s*([A-Z]{2})\s+في\s+(?:النقطة\s+)?([A-Z])\b/g,
      `${SEP}ارسم $1${SEP}ارسم $2${SEP}قطراه $1 و $2 يتقاطعان في $3`
    )
    .replace(
      /توصيل\s+الرؤوس\s+([A-Z])\s*[,،]\s*([A-Z])\s*[,،و]\s*([A-Z])\s+بالأقطار/g,
      `${SEP}ارسم $1$2${SEP}ارسم $2$3${SEP}ارسم $1$3`
    );

  // 5. امتدادات أضلاع المضلعات المتقاطعة خارجياً
  out = out
    .replace(
      /(?:مُد|نمد|مد)\s+(?:الضلع\s+)?([A-Z]{2})\s+إلى\s+([A-Z])\s+ومُد\s+(?:الضلع\s+)?([A-Z]{2})\s+إلى\s+([A-Z])\s*(?:بحيث\s*)?(?:تقاطع\s*الامتدادان|فتقاطعا|ليتقاطعا)\s+في\s*(?:النقطة\s+)?([A-Z])\b/g,
      `${SEP}نمد $1 إلى $5${SEP}نمد $3 إلى $5${SEP}$1 ∩ $3 = {$5}${SEP}نمد $1 إلى $2${SEP}نمد $3 إلى $4`
    )
    .replace(
      /(?:مُد|نمد|مد)\s+(?:الضلعان|الضلعين|الشعاعان)?\s*([A-Z]{2})\s*و\s*([A-Z]{2})\s*(?:فتقاطعا|ليتقاطعا|وتقاطعا)\s+في\s*(?:النقطة\s+)?([A-Z])\b/g,
      `${SEP}نمد $1 إلى $3${SEP}نمد $2 إلى $3${SEP}$1 ∩ $2 = {$3}`
    )
    .replace(
      /(?:([A-Z]{6})\s+سداسي\s+منتظم|سداسي\s+منتظم\s+([A-Z]{6}))\s+ممتدة\s+أضلاعه\s+البديلة\s+لتكون\s+مثلث(?:اً|ا)?(?:\s+كبير(?:اً|ا)?)?\s+([A-Z]{3})\b/g,
      (_m, h1: string | undefined, h2: string | undefined, tri: string) => {
        const hex = h1 ?? h2!;
        return `سداسي منتظم ${hex}${SEP}${hex[0]}${hex[1]} ∩ ${hex[2]}${hex[3]} = {${tri[0]}}${SEP}${hex[2]}${hex[3]} ∩ ${hex[4]}${hex[5]} = {${tri[1]}}${SEP}${hex[4]}${hex[5]} ∩ ${hex[0]}${hex[1]} = {${tri[2]}}`;
      }
    )
    .replace(
      /(?:مُدت|مدت)\s+أضلاعه(?:\s+البديلة)?\s*(?:([A-Z]{2})\s*[,،و]\s*([A-Z]{2})\s*[,،و]\s*([A-Z]{2})\s*)?(?:لتلتقي[^؛;]*?وتشكل|لتكون)\s+مثلث(?:اً|ا)?(?:\s+كبير(?:اً|ا)?)?\s+([A-Z]{3})\b/g,
      (_m, s1?: string, s2?: string, s3?: string, tri?: string) =>
        s1 && s2 && s3 && tri
          ? `${SEP}${s1} ∩ ${s2} = {${tri[0]}}${SEP}${s2} ∩ ${s3} = {${tri[1]}}${SEP}${s3} ∩ ${s1} = {${tri[2]}}`
          : `${SEP}`
    );

  return out;
}
