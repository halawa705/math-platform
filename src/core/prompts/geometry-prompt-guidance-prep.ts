import type { MathNotationLanguage } from "../ssot/numeral-and-unit-ssot";

export const MODULE_ID_GEOMETRY_PROMPT_GUIDANCE_PREP =
  "geometry_prompt_guidance_prep" as const;

export function buildPrepStageFigurePromptGuidance(
  notationLanguage: MathNotationLanguage = "english"
): string {
  if (notationLanguage === "arabic") {
    return "📐 توجيه الإخراج الهندسي للإعدادي وحساب المثلثات: لكل شكل اكتب `[رسم هندسي: ...]` كحقائق بـ `;` بلا كود: الرؤوس (مثلث أ ب جـ قائم في ب|أ ب جـ د شبه منحرف|خماسي منتظم أ ب جـ د هـ) ؛ أطوال الأضلاع ووحداتها (أ ب = 6 سم) ؛ الزوايا والتعامد (ق(∠ب) = 60° ؛ ق(∠د) المنعكسة = 215° ؛ أ د ⊥ ب جـ) ؛ الروابط (ب، جـ، هـ على استقامة واحدة ؛ ب هـ ∩ د و = {جـ} ؛ نمد ب جـ إلى هـ) ؛ و`المطلوب: طول أ جـ`. والنظري/حساب الأقطار والمحاور بلا وسم.";
  }
  return "📐 توجيه الإخراج الهندسي للإعدادي وحساب المثلثات: لكل شكل اكتب `[رسم هندسي: ...]` كحقائق بـ `;` بلا كود: الرؤوس (مثلث ABC قائم في B|ABCD شبه منحرف|خماسي منتظم ABCDE|ABCD ~ EFGH) ؛ أطوال الأضلاع ووحداتها (AB = 6 سم) ؛ الزوايا (m(∠B) = 60° ; m(منعكسة ∠D) = 215° ; DE // BC) ؛ الروابط (B, C, E على استقامة واحدة ; BE ∩ DF = {C} ; نمد BC إلى E) ؛ و`المطلوب: طول AC`. والنظري/حساب الأقطار والمحاور بلا وسم.";
}
